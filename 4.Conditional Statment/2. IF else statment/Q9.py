# Write a Python program to:
# Take a number from the user
# If the number is greater than or equal to 100, print:
# Century Number
# Otherwise, print:
# Less than Century
# Example
# Input:
# 120
# Output:
# Century Number
# Write your code 👨‍💻

number = int(input("Enter a number: "))
if number >= 100:
    print("Century Number")
else:
    print("Less than Century")