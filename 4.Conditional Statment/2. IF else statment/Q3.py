# Write a Python program to:
# Take the user's age as input
# If age is 18 or above, print:
# Eligible for Voting
# Otherwise, print:
# Not Eligible for Voting
# Example
# Input:
# 16
# Output:
# Not Eligible for Voting
# Write your code 👨‍💻

age = int(input("Enter your age: "))
if age >= 18:
    print("Eligible for Voting")
else:
    print("Not Eligible for Voting")