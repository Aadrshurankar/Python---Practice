# Take a number from the user
# If the number is positive, print:
# Positive Number
# Else if the number is negative, print:
# Negative Number
# Otherwise, print:
# Zero
# Example
# Input:
# 0
# Output:
# Zero
# Write your code 👨‍💻

number = float(input("Enter a number: "))
if number > 0:
    print("Positive Number")
elif number < 0:
    print("Negative Number")
else:
    print("Zero")